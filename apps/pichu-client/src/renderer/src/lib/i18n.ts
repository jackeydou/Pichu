const DICTIONARIES = {
  en: EN,
  'zh-CN': ZH_CN
}

export type I18nKey = keyof typeof EN
export type AppLanguage = keyof typeof DICTIONARIES

const TRADITIONAL_CHINESE_REGIONS = new Set(['HK', 'MO', 'TW'])
const SIMPLIFIED_CHINESE_REGIONS = new Set(['CN', 'MY', 'SG'])

function canonicalizeLanguageTag(value: string): string | null {
  try {
    return Intl.getCanonicalLocales(value)[0] ?? null
  } catch {
    return null
  }
}

function matchSupportedLanguage(value: string): AppLanguage | null {
  const canonicalLanguage = canonicalizeLanguageTag(value.trim())
  if (!canonicalLanguage) {
    return null
  }

  const locale = new Intl.Locale(canonicalLanguage)
  const language = locale.language.toLowerCase()
  if (language === 'en') {
    return 'en'
  }
  if (language !== 'zh') {
    return null
  }

  const script = locale.script?.toLowerCase()
  if (script === 'hans') {
    return 'zh-CN'
  }
  if (script === 'hant') {
    return null
  }

  const region = locale.region?.toUpperCase()
  if (region && TRADITIONAL_CHINESE_REGIONS.has(region)) {
    return null
  }
  if (region && SIMPLIFIED_CHINESE_REGIONS.has(region)) {
    return 'zh-CN'
  }

  return 'zh-CN'
}

function detectSystemLanguage(): AppLanguage {
  const languages = [...(navigator.languages ?? []), navigator.language].filter(Boolean)
  for (const language of languages) {
    const matchedLanguage = matchSupportedLanguage(language)
    if (matchedLanguage) {
      return matchedLanguage
    }
  }
  return 'en'
}

function normalizeLanguage(language: string | undefined): AppLanguage {
  if (language === 'auto') {
    return detectSystemLanguage()
  }
  return language === 'zh-CN' ? 'zh-CN' : 'en'
}

function applyI18nLanguage(language: AppLanguage): void {
  if (i18next.language !== language) {
    void i18next.changeLanguage(language)
  }
}

void i18next.use(initReactI18next).init({
  resources: {
    en: {
      translation: EN
    },
    'zh-CN': {
      translation: ZH_CN
    }
  },
  lng: normalizeLanguage(useSettingsStore.getState().language),
  fallbackLng: 'en',
  supportedLngs: ['en', 'zh-CN'],
  interpolation: {
    escapeValue: false
  },
  react: {
    useSuspense: false
  }
})

useSettingsStore.subscribe((state, previousState) => {
  if (state.language !== previousState.language) {
    applyI18nLanguage(normalizeLanguage(state.language))
  }
})

export function useI18n(): {
  language: AppLanguage
  t: (key: I18nKey, options?: Record<string, unknown>) => string
} {
  const language = useSettingsStore((state) => normalizeLanguage(state.language))
  const { t: translate } = useTranslation()
  const t = useCallback(
    (key: I18nKey, options?: Record<string, unknown>) => String(translate(key, options)),
    [translate]
  )

  return {
    language,
    t
  }
}
